AREA Enable_IRQ, CODE, READONLY
ENTRY

MRS R1, CPSR
BIC R1, R1, #0X80
MSR CPSR_C, R1

BACK B BACK

END


AREA Enable_FIQ, CODE, READONLY
ENTRY

MRS R1, CPSR
BIC R1, R1, #0X40
MSR CPSR_C, R1

BACK B BACK

END


AREA Disable_FIQ, CODE, READONLY
ENTRY

MRS R1, CPSR
ORR R1, R1, #0X40
MSR CPSR_C, R1

BACK B BACK

END




AREA Disable_IRQ, CODE, READONLY
ENTRY

MRS R1, CPSR
ORR R1, R1, #0X80
MSR CPSR_C, R1

BACK B BACK

END
